-- H2 database creation commands for KT-3.
-- With ddl-auto=update Hibernate creates matching tables automatically for local practice.
-- To use this SQL file manually, first turn ddl-auto to none and run the statements on an empty database.
CREATE TABLE course_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(255) NOT NULL UNIQUE
);
CREATE TABLE tasks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(255) NOT NULL,
 description VARCHAR(4000),
 priority VARCHAR(255),
 status VARCHAR(255),
 created_at TIMESTAMP,
 owner_id BIGINT,
 CONSTRAINT fk_task_owner FOREIGN KEY (owner_id) REFERENCES course_users(id)
);
CREATE TABLE tags (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(255) NOT NULL UNIQUE
);
CREATE TABLE task_tags (
 task_id BIGINT NOT NULL,
 tag_id BIGINT NOT NULL,
 PRIMARY KEY (task_id,tag_id),
 CONSTRAINT fk_ttag_task FOREIGN KEY (task_id) REFERENCES tasks(id),
 CONSTRAINT fk_ttag_tag FOREIGN KEY (tag_id) REFERENCES tags(id)
);
CREATE INDEX idx_tasks_priority ON tasks(priority);
CREATE INDEX idx_tasks_status ON tasks(status);
